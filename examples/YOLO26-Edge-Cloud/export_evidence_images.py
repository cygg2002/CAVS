"""Export qualitative evidence images for edge-cloud detection comparisons.

The script searches a YOLO/COCO-style validation set for images where the
deployable edge-cloud policy has higher per-image detection quality than
cloud-only YOLO26x. Per-image AP is only a diagnostic proxy; official mAP is
still the dataset-level metric reported by evaluate_edge_cloud.py.
"""

