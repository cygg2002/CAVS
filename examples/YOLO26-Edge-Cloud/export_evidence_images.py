COLORS = {
    "gt": (0, 215, 255),
    "edge": (60, 220, 60),
    "cloud": (255, 140, 0),
    "fused": (60, 90, 255),
}


def parse_args() -> argparse.Namespace:
    """Parse command-line arguments."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", required=True, help="Image directory or manifest txt.")
    parser.add_argument("--edge-model", default="yolo26s.pt")
    parser.add_argument("--cloud-model", default="yolo26x.pt")
    parser.add_argument("--policy-path", required=True)
    parser.add_argument("--save-dir", default="runs/edge_cloud/evidence_images")
    parser.add_argument("--device", default="0")
    parser.add_argument("--imgsz", type=int, default=640)
    parser.add_argument("--cloud-imgsz", type=int, default=512)
    parser.add_argument("--conf", type=float, default=0.25)
    parser.add_argument("--cloud-conf", type=float, default=0.25)
    parser.add_argument("--jpeg-quality", type=int, default=80)
    parser.add_argument("--learned-frame-threshold", type=float, default=0.60)
    parser.add_argument("--learned-roi-threshold", type=float, default=0.08)
    parser.add_argument("--learned-cost-weight", type=float, default=0.02)
    parser.add_argument("--learned-max-roi-per-image", type=int, default=1)
    parser.add_argument("--roi-expand", type=float, default=1.35)
    parser.add_argument("--roi-small-gain", type=float, default=1.6)
    parser.add_argument("--roi-edge-gain", type=float, default=1.45)
    parser.add_argument("--roi-large-gain", type=float, default=1.15)
    parser.add_argument("--roi-extra-cloud-conf", type=float, default=0.55)
    parser.add_argument("--roi-veto-edge-conf", type=float, default=0.25)
    parser.add_argument("--iou-match", type=float, default=0.5)
    parser.add_argument("--fused-nms-iou", type=float, default=0.7)
    parser.add_argument("--target-count", type=int, default=10)
    parser.add_argument("--require-person", action=argparse.BooleanOptionalAction, default=True)
    parser.add_argument("--min-gt-classes", type=int, default=3)
    parser.add_argument("--min-ap-margin", type=float, default=0.03)
    parser.add_argument(
        "--selection-mode",
        choices=["quality", "box_count"],
        default="quality",
        help="quality selects AP/F1 evidence; box_count selects cases where edge-cloud has more boxes.",
    )
    parser.add_argument("--min-count-margin", type=int, default=1)
    parser.add_argument("--max-edge-cloud-boxes", type=int, default=0, help="0 disables the upper box-count limit.")
    parser.add_argument(
        "--compare-to",
        choices=["cloud", "edge", "both"],
        default="cloud",
        help="Select evidence where edge-cloud beats cloud-only, edge-only, or both.",
    )
    parser.add_argument(
        "--route-filter",
        choices=["any", "full_cloud", "roi_cloud", "edge_no_upload"],
        default="any",
        help="Keep only evidence generated by the selected edge-cloud route.",
    )
    parser.add_argument("--max-candidates", type=int, default=0, help="0 means scan all matching images.")
    return parser.parse_args()


def greedy_stats(preds: list[dict[str, Any]], labels: list[dict[str, Any]], iou_thr: float = 0.5) -> dict[str, float]:
    """Return TP/FP/FN and F1 for one image at one IoU threshold."""
    used: set[int] = set()
    tp = 0
    fp = 0
    for pred in sorted(preds, key=lambda item: float(item.get("conf", 0.0)), reverse=True):
        best_idx = None
        best_iou = 0.0
        for idx, label in enumerate(labels):
            if idx in used or int(label["cls"]) != int(pred["cls"]):
                continue
            iou = box_iou(pred["xyxy"], label["xyxy"])
            if iou > best_iou:
                best_idx = idx
                best_iou = iou
        if best_idx is not None and best_iou >= iou_thr:
            used.add(best_idx)
            tp += 1
        else:
            fp += 1
    fn = max(0, len(labels) - tp)
    denom = 2 * tp + fp + fn
    f1 = (2 * tp / denom) if denom else 0.0
    return {"tp": float(tp), "fp": float(fp), "fn": float(fn), "f1": float(f1)}


def ap_for_class(preds: list[dict[str, Any]], labels: list[dict[str, Any]], cls_id: int, iou_thr: float) -> float:
    """Compute a small per-image AP proxy for one class and IoU threshold."""
    cls_labels = [label for label in labels if int(label["cls"]) == cls_id]
    if not cls_labels:
        return 0.0
    cls_preds = [pred for pred in preds if int(pred["cls"]) == cls_id]
    if not cls_preds:
        return 0.0
    cls_preds.sort(key=lambda item: float(item.get("conf", 0.0)), reverse=True)
    used: set[int] = set()
    tp = []
    fp = []
    for pred in cls_preds:
        best_idx = None
        best_iou = 0.0
        for idx, label in enumerate(cls_labels):
            if idx in used:
                continue
            iou = box_iou(pred["xyxy"], label["xyxy"])
            if iou > best_iou:
                best_idx = idx
                best_iou = iou
        if best_idx is not None and best_iou >= iou_thr:
            used.add(best_idx)
            tp.append(1.0)
            fp.append(0.0)
        else:
            tp.append(0.0)
            fp.append(1.0)
    tp_cum = np.cumsum(np.asarray(tp, dtype=np.float64))
    fp_cum = np.cumsum(np.asarray(fp, dtype=np.float64))
    recall = tp_cum / max(1, len(cls_labels))
    precision = tp_cum / np.maximum(tp_cum + fp_cum, 1e-9)
    ap = 0.0
    for r in np.linspace(0.0, 1.0, 101):
        valid = precision[recall >= r]
        ap += float(valid.max()) if valid.size else 0.0
    return ap / 101.0


def per_image_ap_proxy(preds: list[dict[str, Any]], labels: list[dict[str, Any]]) -> float:
    """Compute a per-image COCO-style AP proxy over GT classes and IoU thresholds."""
    classes = sorted({int(label["cls"]) for label in labels})
    if not classes:
        return 0.0
    values = []
    for thr in np.linspace(0.5, 0.95, 10):
        for cls_id in classes:
            values.append(ap_for_class(preds, labels, cls_id, float(thr)))
    return float(np.mean(values)) if values else 0.0


def draw_boxes(
    image: np.ndarray,
    boxes: list[dict[str, Any]],
    names: dict[int, str],
    color: tuple[int, int, int],
    title: str,
    show_conf: bool = True,
) -> np.ndarray:
    """Draw boxes and a panel title."""
    canvas = image.copy()
    h, w = canvas.shape[:2]
    font_scale = max(0.45, min(0.8, w / 1200.0))
    thickness = max(1, int(round(w / 500.0)))
    cv2.rectangle(canvas, (0, 0), (w, 34), (0, 0, 0), -1)
    cv2.putText(canvas, title, (10, 24), cv2.FONT_HERSHEY_SIMPLEX, 0.75, (255, 255, 255), 2, cv2.LINE_AA)
    for box in boxes:
        x1, y1, x2, y2 = [int(round(v)) for v in box["xyxy"]]
        x1, y1 = max(0, x1), max(0, y1)
        x2, y2 = min(w - 1, x2), min(h - 1, y2)
        label = names.get(int(box["cls"]), str(box["cls"]))
        if show_conf and "conf" in box:
            label = f"{label} {float(box['conf']):.2f}"
        cv2.rectangle(canvas, (x1, y1), (x2, y2), color, thickness)
        (tw, th), _ = cv2.getTextSize(label, cv2.FONT_HERSHEY_SIMPLEX, font_scale, thickness)
        y_text = max(34 + th + 2, y1)
        cv2.rectangle(canvas, (x1, y_text - th - 5), (min(w - 1, x1 + tw + 4), y_text + 3), color, -1)
        cv2.putText(
            canvas,
            label,
            (x1 + 2, y_text),
            cv2.FONT_HERSHEY_SIMPLEX,
            font_scale,
            (0, 0, 0),
            max(1, thickness),
            cv2.LINE_AA,
        )
    return canvas


def make_comparison(panels: list[np.ndarray]) -> np.ndarray:
    """Create a 2x2 comparison grid."""
    h = min(panel.shape[0] for panel in panels)
    resized = []
    for panel in panels:
        scale = h / max(1, panel.shape[0])
        resized.append(cv2.resize(panel, (int(round(panel.shape[1] * scale)), h)))
    max_w = max(panel.shape[1] for panel in resized)
    padded = []
    for panel in resized:
        if panel.shape[1] < max_w:
            pad = np.full((h, max_w - panel.shape[1], 3), 245, dtype=np.uint8)
            panel = np.hstack([panel, pad])
        padded.append(panel)
    return np.vstack([np.hstack(padded[:2]), np.hstack(padded[2:])])


def run_edge_cloud(
    image: np.ndarray,
    edge_boxes: list[dict[str, Any]],
    cloud_model: YOLO,
    policy: dict[str, Any],
    args: argparse.Namespace,
) -> tuple[list[dict[str, Any]], dict[str, Any]]:
    """Run the deployable learned v2 edge-cloud decision for one image."""
    final_boxes = [dict(box) for box in edge_boxes]
    context = image_context(image, edge_boxes)
    full_frame_kb = len(encode_jpeg(image, args.jpeg_quality)) / 1024.0
    frame_eval = policy_decision(
        policy,
        "frame",
        frame_features(context, policy.get("frame_features")),
        full_frame_kb,
        args.learned_cost_weight,
    )
    if frame_eval["probability"] >= args.learned_frame_threshold and frame_eval["decision"] > 0.0:
        ns = SimpleNamespace(**vars(args))
        cloud_boxes, cloud_latency = cloud_predict(cloud_model, image, ns, args.cloud_imgsz, conf=args.cloud_conf)
        return class_aware_nms(cloud_boxes, args.fused_nms_iou), {
            "route": "full_cloud",
            "frame_probability": frame_eval["probability"],
            "frame_expected_gain": frame_eval["expected_gain"],
            "frame_decision": frame_eval["decision"],
            "payload_kb": full_frame_kb,
            "cloud_latency_ms": cloud_latency,
            "roi_probability": 0.0,
        }

    roi_candidates = []
    for edge_index, box in enumerate(edge_boxes):
        roi_gain = adaptive_roi_gain(
            box,
            image.shape[:2],
            base_gain=args.roi_expand,
            small_gain=args.roi_small_gain,
            edge_gain=args.roi_edge_gain,
            large_gain=args.roi_large_gain,
        )
        crop_xyxy = expand_xyxy(box["xyxy"], image.shape[:2], roi_gain)
        x1, y1, x2, y2 = crop_xyxy
        crop_ratio = max(0.0, (x2 - x1) * (y2 - y1)) / max(1.0, float(image.shape[0] * image.shape[1]))
        estimated_kb = max(1.0, full_frame_kb * crop_ratio)
        roi_eval = policy_decision(
            policy,
            "roi",
            roi_features(box, image.shape[:2], context, policy.get("roi_features")),
            estimated_kb,
            args.learned_cost_weight,
        )
        if roi_eval["probability"] >= args.learned_roi_threshold and roi_eval["decision"] > 0.0:
            roi_candidates.append(
                (
                    roi_eval["decision"],
                    roi_eval["probability"],
                    roi_eval["expected_gain"],
                    estimated_kb,
                    edge_index,
                    box,
                    crop_xyxy,
                )
            )
    roi_candidates.sort(key=lambda item: item[0], reverse=True)
    used_payload = 0.0
    cloud_latency_ms = 0.0
    chosen = roi_candidates[: args.learned_max_roi_per_image]
    for _, prob, _, estimated_kb, edge_index, box, crop_xyxy in chosen:
        crop = crop_image(image, crop_xyxy)
        ns = SimpleNamespace(**vars(args))
        cloud_boxes, cloud_latency = cloud_predict(cloud_model, crop, ns, args.cloud_imgsz, conf=args.cloud_conf)
        cloud_boxes = shift_boxes(cloud_boxes, (crop_xyxy[0], crop_xyxy[1]))
        final_boxes = apply_roi_cloud(
            final_boxes,
            edge_index,
            cloud_boxes,
            args.iou_match,
            args.cloud_conf,
            args.roi_extra_cloud_conf,
            args.roi_veto_edge_conf,
        )
        used_payload += estimated_kb
        cloud_latency_ms += cloud_latency
    route = "roi_cloud" if chosen else "edge_no_upload"
    return class_aware_nms(final_boxes, args.fused_nms_iou), {
        "route": route,
        "frame_probability": frame_eval["probability"],
        "frame_expected_gain": frame_eval["expected_gain"],
        "frame_decision": frame_eval["decision"],
        "payload_kb": used_payload,
        "cloud_latency_ms": cloud_latency_ms,
        "roi_probability": float(chosen[0][1]) if chosen else 0.0,
    }


def main() -> None:
    """Run evidence export."""
    args = parse_args()
    save_dir = Path(args.save_dir)
    save_dir.mkdir(parents=True, exist_ok=True)
    names = load_coco_names()
    image_paths = collect_image_paths(args.source)
    edge_model = YOLO(args.edge_model)
    cloud_model = YOLO(args.cloud_model)
    policy = load_policy(args.policy_path)
    rows: list[dict[str, Any]] = []
    scanned = 0

    for image_path in image_paths:
        image = cv2.imread(str(image_path))
        if image is None:
            continue
        labels = load_labels(image_path, image.shape[:2])
        gt_classes = sorted({int(label["cls"]) for label in labels})
        if args.require_person and 0 not in gt_classes:
            continue
        if len(gt_classes) < args.min_gt_classes:
            continue
        scanned += 1
        if args.max_candidates and scanned > args.max_candidates:
            break

        edge_result = edge_model.predict(source=image, imgsz=args.imgsz, conf=args.conf, device=args.device, verbose=False)[0]
        cloud_result = cloud_model.predict(
            source=image, imgsz=args.cloud_imgsz, conf=args.cloud_conf, device=args.device, verbose=False
        )[0]
        edge_boxes = boxes_from_result(edge_result)
        cloud_boxes = boxes_from_result(cloud_result)
        edge_cloud_boxes, decision = run_edge_cloud(image, edge_boxes, cloud_model, policy, args)
        if args.route_filter != "any" and decision["route"] != args.route_filter:
            continue

        edge_ap = per_image_ap_proxy(edge_boxes, labels)
        cloud_ap = per_image_ap_proxy(cloud_boxes, labels)
        ec_ap = per_image_ap_proxy(edge_cloud_boxes, labels)
        edge_stats = greedy_stats(edge_boxes, labels)
        cloud_stats = greedy_stats(cloud_boxes, labels)
        ec_stats = greedy_stats(edge_cloud_boxes, labels)
        margin_vs_cloud = ec_ap - cloud_ap
        margin_vs_edge = ec_ap - edge_ap
        f1_margin_vs_cloud = ec_stats["f1"] - cloud_stats["f1"]
        f1_margin_vs_edge = ec_stats["f1"] - edge_stats["f1"]
        edge_count = len(edge_boxes)
        cloud_count = len(cloud_boxes)
        edge_cloud_count = len(edge_cloud_boxes)
        if args.selection_mode == "box_count":
            margin_vs_cloud_count = edge_cloud_count - cloud_count
            margin_vs_edge_count = edge_cloud_count - edge_count
            keep = (
                margin_vs_cloud_count >= args.min_count_margin
                and margin_vs_edge_count >= args.min_count_margin
                and (args.max_edge_cloud_boxes <= 0 or edge_cloud_count <= args.max_edge_cloud_boxes)
            )
            sort_margin = min(margin_vs_cloud_count, margin_vs_edge_count)
            sort_f1_margin = -edge_cloud_count
        elif args.compare_to == "cloud":
            keep = margin_vs_cloud > args.min_ap_margin and f1_margin_vs_cloud > 0.0
            sort_margin = margin_vs_cloud
            sort_f1_margin = f1_margin_vs_cloud
        elif args.compare_to == "edge":
            keep = margin_vs_edge > args.min_ap_margin and f1_margin_vs_edge > 0.0
            sort_margin = margin_vs_edge
            sort_f1_margin = f1_margin_vs_edge
        else:
            keep = (
                margin_vs_cloud > args.min_ap_margin
                and margin_vs_edge > args.min_ap_margin
                and f1_margin_vs_cloud > 0.0
                and f1_margin_vs_edge > 0.0
            )
            sort_margin = min(margin_vs_cloud, margin_vs_edge)
            sort_f1_margin = min(f1_margin_vs_cloud, f1_margin_vs_edge)
        if not keep:
            continue

        rows.append(
            {
                "image": str(image_path),
                "file": image_path.name,
                "route": decision["route"],
                "gt_classes": ",".join(names.get(cls, str(cls)) for cls in gt_classes),
                "edge_ap_proxy": edge_ap,
                "cloud_ap_proxy": cloud_ap,
                "edge_cloud_ap_proxy": ec_ap,
                "edge_boxes": edge_count,
                "cloud_boxes": cloud_count,
                "edge_cloud_boxes": edge_cloud_count,
                "ap_margin_vs_cloud": margin_vs_cloud,
                "ap_margin_vs_edge": margin_vs_edge,
                "edge_f1_50": edge_stats["f1"],
                "cloud_f1_50": cloud_stats["f1"],
                "edge_cloud_f1_50": ec_stats["f1"],
                "f1_margin_vs_cloud": f1_margin_vs_cloud,
                "f1_margin_vs_edge": f1_margin_vs_edge,
                "_sort_margin": sort_margin,
                "_sort_f1_margin": sort_f1_margin,
                "edge_tp": edge_stats["tp"],
                "edge_fp": edge_stats["fp"],
                "edge_fn": edge_stats["fn"],
                "cloud_tp": cloud_stats["tp"],
                "cloud_fp": cloud_stats["fp"],
                "cloud_fn": cloud_stats["fn"],
                "edge_cloud_tp": ec_stats["tp"],
                "edge_cloud_fp": ec_stats["fp"],
                "edge_cloud_fn": ec_stats["fn"],
                "frame_probability": decision["frame_probability"],
                "frame_expected_gain": decision["frame_expected_gain"],
                "frame_decision": decision["frame_decision"],
                "roi_probability": decision["roi_probability"],
                "payload_kb": decision["payload_kb"],
                "_image": image,
                "_labels": labels,
                "_edge_boxes": edge_boxes,
                "_cloud_boxes": cloud_boxes,
                "_edge_cloud_boxes": edge_cloud_boxes,
            }
        )

    rows.sort(key=lambda item: (item["_sort_margin"], item["_sort_f1_margin"]), reverse=True)
    selected = rows[: args.target_count]
    csv_rows = []
    for rank, row in enumerate(selected, start=1):
        stem = f"{rank:02d}_{Path(row['file']).stem}"
        out_dir = save_dir / stem
        out_dir.mkdir(parents=True, exist_ok=True)
        image = row.pop("_image")
        labels = row.pop("_labels")
        edge_boxes = row.pop("_edge_boxes")
        cloud_boxes = row.pop("_cloud_boxes")
        edge_cloud_boxes = row.pop("_edge_cloud_boxes")
        gt_panel = draw_boxes(image, labels, names, COLORS["gt"], f"GT | {row['file']}", show_conf=False)
        edge_panel = draw_boxes(image, edge_boxes, names, COLORS["edge"], "YOLO26s edge")
        cloud_panel = draw_boxes(image, cloud_boxes, names, COLORS["cloud"], "YOLO26x cloud-only")
        ec_panel = draw_boxes(image, edge_cloud_boxes, names, COLORS["fused"], f"Edge-cloud v2 | {row['route']}")
        comparison = make_comparison([gt_panel, edge_panel, cloud_panel, ec_panel])
        cv2.imwrite(str(out_dir / "gt.jpg"), gt_panel)
        cv2.imwrite(str(out_dir / "yolo26s.jpg"), edge_panel)
        cv2.imwrite(str(out_dir / "yolo26x.jpg"), cloud_panel)
        cv2.imwrite(str(out_dir / "edge_cloud_v2.jpg"), ec_panel)
        cv2.imwrite(str(out_dir / "comparison.jpg"), comparison)
        row["rank"] = rank
        row["output_dir"] = str(out_dir)
        row.pop("_sort_margin", None)
        row.pop("_sort_f1_margin", None)
        csv_rows.append(row)

    csv_path = save_dir / "evidence_summary.csv"
    if csv_rows:
        fieldnames = [key for key in csv_rows[0].keys()]
        with csv_path.open("w", newline="", encoding="utf-8") as f:
            writer = csv.DictWriter(f, fieldnames=fieldnames)
            writer.writeheader()
            writer.writerows(csv_rows)
    summary = {
        "source": args.source,
        "scanned_matching_images": scanned,
        "selected": len(csv_rows),
        "policy": args.policy_path,
        "frame_threshold": args.learned_frame_threshold,
        "roi_threshold": args.learned_roi_threshold,
        "cloud_imgsz": args.cloud_imgsz,
        "compare_to": args.compare_to,
        "route_filter": args.route_filter,
        "selection_mode": args.selection_mode,
        "min_count_margin": args.min_count_margin,
        "max_edge_cloud_boxes": args.max_edge_cloud_boxes,
        "note": "Per-image AP proxy is for evidence selection only; official mAP is dataset-level.",
        "csv": str(csv_path),
    }
    (save_dir / "summary.json").write_text(json.dumps(summary, indent=2, ensure_ascii=False), encoding="utf-8")
    print(json.dumps(summary, indent=2, ensure_ascii=False))


if __name__ == "__main__":
    main()
