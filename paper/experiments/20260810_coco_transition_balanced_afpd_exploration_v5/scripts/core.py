"""Pure accounting helpers for the AFPD transition-mass diagnostic."""

from __future__ import annotations

from typing import Sequence

import torch


def action_column_mask(
    action_ids: Sequence[Sequence[str]], action_mask: torch.Tensor, action: str
) -> torch.Tensor:
    """Return an image/action mask without assuming a fixed action column."""

    if action_mask.ndim != 2 or len(action_ids) != action_mask.shape[0]:
        raise ValueError("Action IDs and action mask have incompatible shapes")
    output = torch.zeros_like(action_mask, dtype=torch.bool)
    for row, names in enumerate(action_ids):
        if len(names) > action_mask.shape[1]:
            raise ValueError("More action IDs than tensor columns")
        if len(names) != len(set(map(str, names))):
            raise ValueError("An image contains duplicate action IDs")
        for column, name in enumerate(names):
            if str(name) == str(action):
                output[row, column] = True
    return output & action_mask.to(torch.bool)


def crossing_pair_masks(
    rewards: torch.Tensor,
    costs: torch.Tensor,
    action_mask: torch.Tensor,
    roi_columns: torch.Tensor,
    *,
    maximum_price: float,
) -> tuple[torch.Tensor, torch.Tensor]:
    """Return valid pair crossings and the subset generated by an ROI pair."""

    if rewards.shape != costs.shape or rewards.shape != action_mask.shape:
        raise ValueError("Reward, cost, and action masks must have equal shapes")
    if roi_columns.shape != rewards.shape:
        raise ValueError("ROI column mask has the wrong shape")
    action_count = rewards.shape[1]
    left, right = torch.triu_indices(action_count, action_count, offset=1)
    reward_difference = rewards[:, left] - rewards[:, right]
    cost_difference = costs[:, left] - costs[:, right]
    available = (
        action_mask[:, left].to(torch.bool)
        & action_mask[:, right].to(torch.bool)
        & (cost_difference.abs() > 1e-12)
    )
    safe_difference = torch.where(
        cost_difference.abs() > 1e-12,
        cost_difference,
        torch.ones_like(cost_difference),
    )
    crossing = reward_difference / safe_difference
    valid = (
        available
        & torch.isfinite(crossing)
        & (crossing > 0.0)
        & (crossing < float(maximum_price))
    )
    roi_pair = roi_columns[:, left] | roi_columns[:, right]
    return valid, valid & roi_pair


def safe_fraction(numerator: float, denominator: float) -> float:
    return float(numerator / denominator) if denominator else 0.0

